"""
run_population_validation.py
============================

Released Dataset Validation Pipeline

Purpose
-------
Validate the released ULM-TSST dataset
artifact stored on disk.

Unlike:

    run_physiological_validation.py

which validates a single generated
sample,

this script validates the complete
released dataset.

Validation Scope
----------------

✓ Sample Variability

✓ Subject Variability

✓ Session Variability

✓ Controllability

Dataset Source
--------------

data/generated/ulm_tsst_v1/raw

This script validates the dataset
artifact itself rather than generating
new synthetic samples at runtime.

Outputs
-------

results/
└── population_validation/

    population_validation.json

    population_report.md

    sample_variability.csv

    subject_variability.csv

    session_variability.csv

    controllability.csv

Usage
-----

python -m scripts.run_population_validation
"""

from __future__ import annotations

import sys
from pathlib import Path




# ==========================================================
# Project Root
# ==========================================================

PROJECT_ROOT = (
    Path(__file__)
    .resolve()
    .parent.parent
)

if str(PROJECT_ROOT) not in sys.path:

    sys.path.insert(
        0,
        str(PROJECT_ROOT),
    )


# ==========================================================
# Imports
# ==========================================================

from datasets.loaders.ulm_tsst_disk_dataset import (
    ULMTSSTDiskDataset,
)

from datasets.evaluation.population_validation import (
    PopulationValidator,
)

from datasets.evaluation.population_visualization import (
    PopulationVisualizer,
)


# ==========================================================
# Configuration
# ==========================================================

DATASET_ROOT = Path(
    "data/generated/ulm_tsst_v1"
)

OUTPUT_DIR = Path(
    "results/population_validation"
)

DATASET_SPLIT = "raw"


# ==========================================================
# Load Dataset
# ==========================================================

def load_dataset():
    """
    Load released dataset from disk.

    Uses the official dataset artifact
    generated by the dataset generation
    pipeline.
    """

    return ULMTSSTDiskDataset(

        dataset_root=
        DATASET_ROOT,

        split=
        DATASET_SPLIT,

        device="cpu",
    )


# ==========================================================
# Validation
# ==========================================================

def run_population_validation():

    print(
        "\n"
        + "=" * 80
    )

    print(
        "RELEASED DATASET VALIDATION"
    )

    print(
        "=" * 80
    )

    # ------------------------------------------------------
    # Load Dataset
    # ------------------------------------------------------

    print(
        "\n[1/3] Loading released dataset..."
    )

    dataset = load_dataset()

    print(
        f"Dataset Root : "
        f"{DATASET_ROOT}"
    )

    print(
        f"Split        : "
        f"{DATASET_SPLIT}"
    )

    print(
        f"Dataset Size : "
        f"{len(dataset)} samples"
    )

    # ------------------------------------------------------
    # Validation
    # ------------------------------------------------------

    print(
        "\n[2/3] Running population validation..."
    )

    validator = (
        PopulationValidator()
    )

    summary = (
        validator.validate(

            dataset=dataset,

            output_dir=
            OUTPUT_DIR,
        )
    )

    # ------------------------------------------------------
    # Visualizations
    # ------------------------------------------------------

    print(
        "\n[3/4] Generating visualizations..."
    )

    visualizer = (
        PopulationVisualizer(
            OUTPUT_DIR
        )
    )

    visualizer.generate_all()

    # ------------------------------------------------------
    # Results
    # ------------------------------------------------------

    print(
        "\n[4/4] Validation completed."
    )

    print(
        "\nSummary"
    )

    print(
        "-" * 80
    )

    for key, value in (
        summary.items()
    ):

        print(
            f"{key}: {value}"
        )

    print(
        "\nOutput Directory:"
    )

    print(
        OUTPUT_DIR.resolve()
    )

    print(
        "\nGenerated Files:"
    )

    generated_files = [

        "population_validation.json",

        "population_report.md",

        "sample_variability.csv",

        "subject_variability.csv",

        "session_variability.csv",

        "controllability.csv",

        "plots/valence_distribution.png",

        "plots/arousal_distribution.png",

        "plots/stress_distribution.png",

        "plots/workload_distribution.png",

        "plots/label_correlation_matrix.png",

        "plots/subject_variability.png",

        "plots/session_variability.png",
    ]

    for file_name in generated_files:

        print(
            f"  - {file_name}"
        )

    print(
        "\nPopulation validation finished."
    )


# ==========================================================
# Main
# ==========================================================

def main():

    run_population_validation()


# ==========================================================
# Entry Point
# ==========================================================

if __name__ == "__main__":

    main()