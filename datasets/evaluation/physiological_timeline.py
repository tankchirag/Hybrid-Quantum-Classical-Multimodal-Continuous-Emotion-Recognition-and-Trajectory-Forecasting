"""
physiological_timeline.py
=========================

Physiological Timeline Visualization

Purpose
-------
Visualize the physiological response
generated by the synthetic TSST scenario.

Unlike:

    emotion_timeline.py

which focuses on latent emotional
trajectories,

this module focuses on physiological
responses driven by stress.

The figure allows rapid inspection of:

    Stress
    BPM
    EDA
    EMG
    Respiration

throughout the recording.

Typical Expected Response
-------------------------

Stress ↑
    ↓

BPM ↑

EDA ↑

EMG ↑

RESP changes

Outputs
-------

physiological_timeline.png

Design Goals
------------

✓ Thesis quality

✓ Supervisor friendly

✓ TSST phase visualization

✓ Physiology focused

✓ Dataset agnostic
"""

from __future__ import annotations

from pathlib import Path
from typing import Any
from typing import Dict

import numpy as np
import torch
import matplotlib.pyplot as plt


class PhysiologicalTimelinePlotter:

    EMOTION_LABELS = [
        "valence",
        "arousal",
        "stress",
    ]

    PHYSIOLOGY_SIGNALS = [
        "bpm",
        "ecg",
        "eda",
        "resp",
        "emg",
        "eeg",
        "eye",
    ]

    def __init__(
        self,
        figsize=(18, 22),
        dpi=300,
    ):
        self.figsize = figsize
        self.dpi = dpi

    @staticmethod
    def _to_numpy(x):

        if isinstance(
            x,
            torch.Tensor,
        ):
            return (
                x.detach()
                .cpu()
                .numpy()
            )

        return np.asarray(x)

    @staticmethod
    def _normalize(
        x: np.ndarray,
    ) -> np.ndarray:

        minimum = np.min(x)
        maximum = np.max(x)

        denom = (
            maximum - minimum
        )

        if denom < 1e-8:
            return np.zeros_like(x)

        return (
            x - minimum
        ) / denom

    @staticmethod
    def _smooth_signal(
        signal: np.ndarray,
        window_size: int,
    ) -> np.ndarray:
        """
        Moving-average smoothing.

        Used to convert
        high-frequency physiological
        signals into human-readable
        trends.
        """

        signal = np.asarray(
            signal
        ).astype(float)

        if (
            len(signal)
            < window_size
        ):
            return signal

        kernel = (
            np.ones(window_size)
            / window_size
        )

        return np.convolve(
            signal,
            kernel,
            mode="same",
        )

    @staticmethod
    def _downsample(
        signal: np.ndarray,
        target_points: int = 1500,
    ) -> np.ndarray:
        """
        Downsample large signals for
        visualization purposes.

        Keeps overall trend while
        reducing rendering cost.
        """

        signal = np.asarray(
            signal
        )

        if (
            len(signal)
            <= target_points
        ):
            return signal

        indices = np.linspace(
            0,
            len(signal) - 1,
            target_points,
        ).astype(int)

        return signal[
            indices
        ]

    def _extract_ecg_trend(
        self,
        signal: np.ndarray,
    ) -> np.ndarray:
        """
        ECG activity envelope.

        Removes rapid QRS spikes and
        emphasizes long-term trend.
        """

        signal = np.squeeze(
            signal
        )

        signal = np.square(
            signal
        )

        signal = (
            self._smooth_signal(
                signal,
                window_size=3000,
            )
        )

        signal = (
            self._downsample(
                signal
            )
        )

        return signal

    def _extract_emg_trend(
        self,
        signal: np.ndarray,
    ) -> np.ndarray:
        """
        EMG envelope.

        Approximates muscular
        activation intensity.
        """

        signal = np.squeeze(
            signal
        )

        signal = np.square(
            signal
        )

        signal = (
            self._smooth_signal(
                signal,
                window_size=2000,
            )
        )

        signal = np.sqrt(signal)

        signal = (
            self._downsample(
                signal
            )
        )

        return signal

    def _extract_eda_trend(
        self,
        signal: np.ndarray,
    ) -> np.ndarray:
        """
        Slow electrodermal trend.
        """

        signal = np.squeeze(
            signal
        )

        signal = (
            self._smooth_signal(
                signal,
                window_size=256,
            )
        )

        signal = (
            self._downsample(
                signal
            )
        )

        return signal

    def _extract_resp_trend(
        self,
        signal: np.ndarray,
    ) -> np.ndarray:
        """
        Respiratory activity trend.
        """

        signal = np.squeeze(
            signal
        )

        signal = (
            self._smooth_signal(
                signal,
                window_size=128,
            )
        )

        signal = (
            self._downsample(
                signal
            )
        )

        return signal

    def _extract_eeg_trend(
        self,
        signal: np.ndarray,
    ) -> np.ndarray:
        """
        EEG activity trend.

        Uses signal energy as a
        proxy for neural activity.
        """

        signal = np.squeeze(
            signal
        )

        signal = np.square(
            signal
        )

        signal = (
            self._smooth_signal(
                signal,
                window_size=1024,
            )
        )

        signal = (
            self._downsample(
                signal
            )
        )

        return signal

    def _extract_eye_trend(
        self,
        signal: np.ndarray,
    ) -> np.ndarray:
        """
        Eye activity trend.

        Combines both eye channels
        into a single trajectory.
        """

        signal = np.asarray(
            signal
        )

        if signal.ndim > 1:

            signal = np.mean(
                signal,
                axis=1,
            )

        signal = (
            self._smooth_signal(
                signal,
                window_size=240,
            )
        )

        signal = (
            self._downsample(
                signal
            )
        )

        return signal

    def _extract_bpm_trend(
        self,
        signal: np.ndarray,
    ) -> np.ndarray:
        """
        BPM trend.
        """

        signal = np.squeeze(
            signal
        )

        signal = (
            self._smooth_signal(
                signal,
                window_size=5,
            )
        )

        return signal


    @staticmethod
    def _time_axis(
        length: int,
        duration: float,
    ):

        return np.linspace(
            0,
            duration,
            length,
        )

    def plot(
        self,
        sample: Dict[str, Any],
        output_file: str | Path,
    ) -> None:

        metadata = sample[
            "metadata"
        ]

        duration = metadata.get(
            "duration_seconds",
            300,
        )

        labels = sample[
            "continuous_labels"
        ]

        modalities = sample[
            "modalities"
        ]

        valence = self._normalize(
            self._to_numpy(
                labels["valence"]
            )
        )

        arousal = self._normalize(
            self._to_numpy(
                labels["arousal"]
            )
        )

        stress = self._normalize(
            self._to_numpy(
                labels["stress"]
            )
        )

        bpm = self._normalize(
            self._extract_bpm_trend(
                self._to_numpy(
                    modalities["bpm"]
                )
            )
        )

        ecg = self._normalize(
            self._extract_ecg_trend(
                self._to_numpy(
                    modalities["ecg"]
                )
            )
        )

        eda = self._normalize(
            self._extract_eda_trend(
                self._to_numpy(
                    modalities["eda"]
                )
            )
        )

        resp = self._normalize(
            self._extract_resp_trend(
                self._to_numpy(
                    modalities["resp"]
                )
            )
        )

        emg = self._normalize(
            self._extract_emg_trend(
                self._to_numpy(
                    modalities["emg"]
                )
            )
        )

        eeg = self._normalize(
            self._extract_eeg_trend(
                self._to_numpy(
                    modalities["eeg"]
                )
            )
        )

        eye = self._normalize(
            self._extract_eye_trend(
                self._to_numpy(
                    modalities["eye"]
                )
            )
        )

        trajectories = [

            ("Valence", valence),

            ("Arousal", arousal),

            ("Stress", stress),

            ("BPM", bpm),

            ("ECG Trend", ecg),

            ("EDA Trend", eda),

            ("RESP Trend", resp),

            ("EMG Activity", emg),

            ("EEG Activity", eeg),

            ("Eye Activity", eye),
        ]

        n_plots = len(
            trajectories
        )

        fig, axes = plt.subplots(
            n_plots,
            1,
            figsize=self.figsize,
            sharex=True,
        )

        if n_plots == 1:
            axes = [axes]

        fig.suptitle(
            (
                "Physiological Timeline\n"
                f"Subject "
                f"{metadata.get('subject_id', 'N/A')} | "
                f"Session "
                f"{metadata.get('session_id', 'N/A')}"
            ),
            fontsize=16,
            fontweight="bold",
        )



        for ax, (
            title,
            values
        ) in zip(
            axes,
            trajectories,
        ):

            t = np.linspace(
                0,
                duration,
                len(values),
            )

            ax.plot(
                t,
                values,
                linewidth=1.2,
            )

            ax.set_ylabel(
                title,
                fontsize=9,
            )

            ax.set_ylim(
                -0.05,
                1.05,
            )

            ax.grid(
                alpha=0.3,
            )



        # ----------------------------------
        # TSST phase markers
        # ----------------------------------

        phase_lines = [
            duration * 0.20,
            duration * 0.30,
            duration * 0.55,
            duration * 0.80,
        ]

        phase_names = [
            "Preparation",
            "Speech",
            "Arithmetic",
            "Recovery",
        ]

        for ax in axes:

            for x in phase_lines:

                ax.axvline(
                    x,
                    color="red",
                    linestyle=":",
                    alpha=0.5,
                )

        for x, label in zip(
            phase_lines,
            phase_names,
        ):

            axes[0].text(
                x,
                1.02,
                label,
                fontsize=8,
                rotation=90,
                va="bottom",
            )

        axes[-1].set_xlabel(
            "Time (seconds)"
        )

        plt.tight_layout()

        output_file = Path(
            output_file
        )

        output_file.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        plt.savefig(
            output_file,
            dpi=self.dpi,
            bbox_inches="tight",
        )

        plt.close()

    def generate(
        self,
        sample: Dict[str, Any],
        output_directory: str | Path,
    ) -> Path:

        output_directory = Path(
            output_directory
        )

        output_directory.mkdir(
            parents=True,
            exist_ok=True,
        )

        output_file = (
            output_directory
            / "physiological_timeline.png"
        )

        self.plot(
            sample=sample,
            output_file=output_file,
        )

        return output_file